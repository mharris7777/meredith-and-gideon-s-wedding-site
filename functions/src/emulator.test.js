import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { solution, words, puzzleVersion } from './puzzle.js';
const base = process.env.CROSSWORD_TEST_API_URL;
if (!base || !/^http:\/\/127\.0\.0\.1:5001\/demo-[a-z0-9-]+\/us-central1\/crosswordApi$/.test(base)) throw new Error('Emulator tests require a loopback demo project endpoint; never run against production.');
const request = async (action, args = {}) => {
  const r = await fetch(base, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ ...args, action, puzzleVersion }) });
  const data = await r.json();
  return { status: r.status, data };
};
const save = (a, responses, revision, action = 'save', eventId) => request(action, { attemptId: a.attemptId, token: a.token, responses, revision, eventId });
test('Firebase saves private responses, computes scores, rejects forged access, and ranks finalized attempts', async () => {
  const { data: a, status } = await request('start', { displayName: 'Emulator Full Score' });
  assert.equal(status, 200); assert.ok(a.token);
  assert.equal((await request('resume', { attemptId: a.attemptId, token: '0'.repeat(64) })).status, 404);
  const direct = await fetch(`http://127.0.0.1:8080/v1/projects/demo-wedding-crossword/databases/(default)/documents/crosswordAttempts/${a.attemptId}`);
  assert.equal(direct.status, 403);
  const saved = await save(a, solution, 2); assert.equal(saved.status, 200); assert.equal(saved.data.correctWords, undefined);
  await save(a, {}, 1);
  assert.deepEqual((await request('resume', { attemptId: a.attemptId, token: a.token })).data.responses, solution);
  const event = randomUUID();
  assert.equal((await save(a, solution, 3, 'check', event)).data.checks, 1);
  assert.equal((await save(a, solution, 3, 'check', event)).data.checks, 1);
  const submitted = await save(a, solution, 4, 'submit'); assert.equal(submitted.data.correctWords, 33); assert.ok(submitted.data.submittedAt);
  assert.equal((await save(a, {}, 5)).data.correctWords, 33);
  const { data: b } = await request('start', { displayName: 'Emulator Partial Score' });
  const partial = Object.fromEntries(words[0].cells.map(k => [k, solution[k]]));
  assert.equal((await save(b, { invalid: 'A' }, 1)).status, 400);
  assert.equal((await save(b, partial, 2, 'submit')).data.correctWords, 1);
  const { data: c } = await request('start', { displayName: 'Emulator Unassisted' });
  await save(c, solution, 1, 'submit');
  const board = (await request('leaderboard')).data;
  const full = board.rows.find(r => r.attemptId === a.attemptId), unassisted = board.rows.find(r => r.attemptId === c.attemptId);
  assert.ok(unassisted.rank < full.rank);
  assert.equal(full.responses, undefined); assert.equal(full.tokenHash, undefined); assert.equal(full.token, undefined);
  assert.ok(full.elapsedSeconds >= 1);
  console.log('Emulator verified: Firestore permissions, private saves, restore, stale writes, duplicate checks, score finalization, leaderboard ordering.');
});
